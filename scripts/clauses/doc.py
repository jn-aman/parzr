"""Writes docs/rule-packs/clauses-conjunctions.md (the coverage map) from the rules and their own examples."""
import collections
import core

INTRO = """# Clauses and conjunctions pack: coverage map

`engine/rules/packs/clauses-conjunctions.json` holds {n} rules (id prefix `clause.`). Every rule has a required literal,
a positive and a negative example written for it, and a confidence between {lo} and {hi}. The negatives carry the near
misses: the correct sentence with one linking word, the idiom, the mid-sentence use, the question, the proper noun.
The pack is generated by `scripts/gen-clauses-conjunctions.py` from the tables in `scripts/clauses/*.py`; the generator
refuses a rule whose positive does not become exactly the stated correction (case and sentence start included), whose
negative matches, or whose corrected sentence matches again, and it runs every rule over every other rule's examples.

Three design choices keep the pack quiet:

- **Sentence-anchored.** The doubled-linking-word rules start at a sentence start (`Although …, but …`). A mid-sentence
  "but" after a full main clause is correct, so a rule that is not anchored could not tell the two apart.
- **A clause must look like a clause.** The text between the linking word and the repeat is a subject (pronoun,
  determiner plus noun, or a name) and plain words; a second subject pronoun, a capitalized word or a punctuation mark
  ends the match. The no-comma forms are stricter than the comma forms.
- **Known asides are excluded.** "so they say", "so I hear", "so the story goes", "said so", "told me so", "hence the
  name", "thus far", "however hard" never match.

The base pass `grammar.double_conjunction` (engine/src/clause_repairs.rs) already drops "so" or "but" after a
sentence-initial because / since / as / although / though plus a comma. These rules add the openers it does not read,
the forms with no comma, and the second words it does not know. Where both fire on the same span the engine keeps one.
"""

BASE = """## Covered by base rules or other packs (not repeated here)

| Construction | Covered by |
|---|---|
| Sentence-initial because / since / as / although / though + comma + "so" / "but" | `grammar.double_conjunction` (Rust) |
| Comma splice, run-on, fragment, introductory comma, "and" joining clauses | `punctuation.*` (Rust: structure.rs, clauses.rs, punctuation.rs) |
| Embedded question order ("tell me where is the station") | `grammar.embedded_question_order` |
| "the reason is because" + the / it / we / he / she … | `usage.reason_is_because` |
| "Being that" at a sentence start, "Even thought" | `usage.being_that`, `usage.though_even` |
| "despite of", "despite to", "in spite the", "because him", "in case if", "between 5 or 6", "reason of" | `grammar.despite_of`, `prep.despite_of_more`, `prep.despite_to_verb`, `prep.in_spite_missing_of`, `prep.because_object_pronoun`, `prep.in_case_if`, `prep.between_numbers_or`, `prep.reason_of` |
| "and etc", "no sooner then" | `confuse.eg_and_etc2`, `confuse.than_no_sooner` |
| Split or joined connectors: eventhough, incase, inorder, evenif, aswell, whereever, aslong as, altough, becuase, al though, nomatter, never the less, none the less, in stead, there fore | `spelling.*`, `harper.*`, `grammar.phrase.*` |
| "Neither of them are", "both is", "those who is", "neither … nor" agreement | `agree.*` |
| "will" in a time clause ("when I will arrive", "in case you will need") | `tense.time_clause*` |
| "Not only" followed by a non-inverted clause | `grammar.inversion_not_only` |
| "due to the fact that", "in spite of the fact that" as wordiness | `concise.*` (style) |
| "which" for a person | pronouns pack |
"""

LEFT = """## Deliberately left out

| Construction | Why it is not a rule |
|---|---|
| "not only … but" without "also" | "Not only X but Y" is correct; "also" is optional. Parallelism of X and Y needs a parse. |
| A missing relative pronoun in subject position ("the man came yesterday is …") | The verb cannot be told from a noun or a second clause without a parse. |
| "what" for "that" ("I think what you said") | "I think what you said is right" is correct; "I know what you mean" too. |
| "that that", "had had", "which" versus "that" with commas | Both words are often right in the same frame. |
| "As X, so Y" | A correlative pair ("As you sow, so shall you reap"); the base pass strips it (see "Found in the base passes"). |
| "although … yet", "though … still", "even though" versus "even if" | Correct, or a choice that depends on what the writer knows. |
| "both X as well as Y" inside a sentence, "both … or" | "do both tasks as well as you can" is a comparison; "both … or" may mean "either … or". Only the sentence-initial "Both the X as well as the Y" is a rule. |
| "so that's why", "that's why because" | "So that's why!" is a common correct reaction; with "because" it is unclear which word to drop. |
| "because being late …" | A gerund subject ("Because being late costs money, …") is correct. |
| "who that", "which that", "of which that" | Legitimate in "Who that has seen it …" and "of which that he …". |
| "while during X", "both X and also Y", "though that" | Found correct in real text ("worth noting though that …", "increases supply for both factions and also reduces …"). |
| "because the rain." at a sentence end | Real text has truncated fragments, file names and typos ("because your immature") there. |
| "what ever" / "who ever" / "how ever" in questions | "What ever did he say?" is correct; only "what ever you …", "where ever you …", "when ever you …" are rules. |
| "in as much as", "where as" | Correct in "in as much detail as possible" and "where as a child …". |
| Do-support in embedded questions ("how much does it cost" → "how much it costs") | Needs verb morphology, which a regex cannot compute. |
| "unless you don't", "no matter if", "until when", "till", "than what", "like I said", "as long as", "in order that", "so as to", "while" versus "whereas" | Correct, or dialect, or the writer's choice. |
| Chat shorthand: cuz, coz, tho | Owner policy: shorthand stays as typed. |
"""

BUGS = """## Found in the base passes while writing this pack (reported, not changed)

- `grammar.double_conjunction` strips the correlative "so" in "As you sow, so shall you reap." and the adverb in
  "Since Monday, so far it has worked."
- `punctuation.run_on` splits "She doesn't have the permission set configured." into "She doesn't have. The permission set configured."
- `punctuation.apostrophe` turns "Thus far" into "Thu's far".
- `spelling.real_word` changes "nor" to "not" in "Neither he nor she liked it." and "if" to "of" in "Keep a copy if the shop asks for it."
- `punctuation.comma_splice` splits the correct "No matter how hard the team trained, they could not catch the leaders." into two sentences.
- `punctuation.coordinated_clauses` and `punctuation.introductory_comma` put a comma after the linking word instead of before it in "Although it was cold but he came." ("cold, but, he"); the no-comma rules of this pack win that span.
"""


def write(path):
    by = collections.OrderedDict()
    for r in core.RULES:
        by.setdefault(r.get('_section'), []).append(r)
    lines = [INTRO.format(n=len(core.RULES), lo=min(r['confidence'] for r in core.RULES), hi=max(r['confidence'] for r in core.RULES))]
    for section, rules in core.SECTIONS.items():
        lines.append(f'## {section}\n')
        lines.append('| Rule (`clause.` prefix) | Changes | To |')
        lines.append('|---|---|---|')
        for rid in rules:
            r = next(x for x in core.RULES if x['id'] == rid)
            lines.append(f"| `{rid[len(core.PREFIX):]}` | {r['positive']} | {core.FIXED[rid]} |")
        lines.append('')
    lines.append(BASE)
    lines.append(LEFT)
    lines.append(BUGS)
    open(path, 'w').write('\n'.join(lines))
