#!/usr/bin/env python3
"""Builds engine/rules/packs/nouns-plurals.json and docs/rule-packs/nouns-plurals.md (id prefix noun.).
usage: python3 scripts/nouns-plurals-pack/build.py"""
import collections, json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import core
import fam_uncount, fam_irreg, fam_irreg2, fam_num, fam_apos, fam_quant2, fam_slips  # noqa: F401  (importing a family adds its rules)

if core.ERRORS:
    print('\n'.join(core.ERRORS)); sys.exit(1)
ROOT = core.ROOT
(ROOT / 'engine/rules/packs/nouns-plurals.json').write_text(json.dumps(core.RULES, indent=1, ensure_ascii=False) + '\n')
(HERE / 'expected.json').write_text(json.dumps(core.EXPECTED, indent=1, ensure_ascii=False) + '\n')

sections = collections.OrderedDict()
for sec, construction, ids in core.COVER:
    sections.setdefault(sec, []).append((construction, ids))
out = [f'# Nouns and plurals pack: coverage map\n',
       f'`engine/rules/packs/nouns-plurals.json` holds {len(core.RULES)} rules (id prefix `noun.`), generated by '
       '`scripts/nouns-plurals-pack/build.py` (`python3 scripts/nouns-plurals-pack/build.py` rewrites the JSON and this file). '
       'Every rule has a required literal, a positive and a negative example written for it, and is context-anchored: '
       'a wrong plural is flagged where it stands only when it cannot be a verb, a possessive typed without its apostrophe '
       'or a valid plural in another sense. `scripts/nouns-plurals-pack/e2e.py` runs every example through the built engine.\n']
for sec, rows in sections.items():
    out.append(f'\n## {sec}\n\n| Construction | Rules |\n|---|---|')
    for construction, ids in rows:
        shown = ', '.join(f'`{i[5:] if i.startswith("noun.") else i}`' for i in ids[:8])
        more = f' and {len(ids) - 8} more' if len(ids) > 8 else ''
        out.append(f'| {construction} | {len(ids)} rule(s): {shown}{more} |')
out.append('\n## Covered by base rules or the engine, so not repeated\n')
out.append('| Construction | Owner |\n|---|---|')
for construction, owner in [
    ('informations, advices, equipments, furnitures, homeworks', 'base `grammar.uncountable_*`'),
    ('a/an + an uncountable (an advice, a furniture, a luggage ...), much + plural, many + uncountable, fewer + mass, less + count, amount of + people/things', 'articles-determiners pack (`det.a_*`, `det.much_not_*`, `det.many_not_*`, `det.less_not_*`, `det.fewer_not_*`, `det.amount_not_*`, `det.number_not_amount_*`)'),
    ('a criteria, a phenomena, this criteria / these phenomena', '`det.a_criteria`, `det.a_phenomena`, `det.these_not_this_*`'),
    ('every/each + a plural noun (each students, every childs)', 'engine `grammar.noun_number`, `det.every_person`, `det.every_child`'),
    ('many/several/few/two..twelve + a singular noun (two child, many problem, five knife, three year ago)', 'engine `grammar.noun_number` (forms.rs)'),
    ('1990\'s, two week\'s notice, a years work', '`punctuation.apostrophe`'),
    ('5 year old / 5-years-old / a 30 day trial', '`mod.age_year`, `punctuation.compound_hyphen`'),
    ('one of the + a singular noun, the number of ... are, a number of ... is, people is/are, data is/are, this data are', 'agreement pack (`agree.*`), engine'),
    ('-ys for -ies and -s for -es slips that the spelling pass (`spelling.delete_index`, `spelling.common_misspelling`) already fixes in every sentence tried: countrys, citys, familys, companys, babys, partys, storys, policys, categorys, universitys, factorys, enemys, agencys, bodys, ladys, copys, secretarys, memorys, historys, librarys, abilitys, activitys, communitys, opportunitys, difficultys, technologys, strategys, batterys, trys, studys, carrys, replys, applys, hurrys, cherrys, querys, entrys, propertys, hobbys, supplys and about 70 more; also geeses, mooses, criterias, alumnis, photoes, pianoes, videoes, churchs, dishs, searchs, matchs, coachs, softwares, clothings, potatos, tomatos. They were written, found redundant or harmful (a rule that rewrote the base pass\'s own "the other party\'s" mistake into "parties") and dropped', 'spelling pass'),
    ('"social medias", "feedbacks" without a verb of giving: valid in some registers (feedback loops in science; medias as channels), so only "give/get/receive your feedbacks" is flagged', 'dropped after the false-alarm gate'),
    ('persons, a people, a data scientist, a media company, staff are (British), syllabuses, curriculums, formulas, cactuses', 'valid and left alone on purpose'),
]:
    out.append(f'| {construction} | {owner} |')
out.append('\n## Deliberately not covered\n')
for line in [
    '"5 kms", "3 kgs": unit symbols have no plural in SI and Wikipedia style, but "kms" is common and accepted in much of English-language writing; a Style rule for it fired on correct sentences of the false-alarm corpus and was dropped.',
    'Plurals of proper nouns and surnames ("the Smith\'s are coming"): policy never respells a name, and the names benchmark would catch it.',
    '"hairs", "works", "papers", "moneys", "monies", "damages", "advertisements", "behaviours", "foods", "fruits", "cheeses", "breads": valid plurals in ordinary use (strands, items, types, legal senses).',
    '"his wifes car", "my lifes work", "the wolfs den": possessives typed without the apostrophe; the right fix is a possessive, which depends on the next word, so only the plural reading is flagged and only where a verb or a clause end follows.',
    '"fewer water", "less people": owned by the articles-determiners pack and base grammar rules.',
    'A singular noun after "one of the" (agreement pack owns it) and after digits in general ("Windows 10 user", "Level 5 user"): a model number or a label makes the singular right.',
]:
    out.append(f'- {line}')
(ROOT / 'docs/rule-packs/nouns-plurals.md').write_text('\n'.join(out) + '\n')
print(f'{len(core.RULES)} rules')
