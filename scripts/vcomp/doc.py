"""Writes docs/rule-packs/verb-complements.md from the registered rules (the coverage map)."""
import collections, core

HEAD = """# Verb complementation pack (`vcomp.`)

`engine/rules/packs/verb-complements.json` is generated by `scripts/gen-verb-complements.py` from the construction
tables in `scripts/vcomp/`. A gerund or infinitive fix has to respell the verb ("enjoy to read" to "enjoy reading"),
which a regex replacement cannot compute, so the tables list each verb once and the builders emit the capture groups
that rebuild the right form (plain, silent e, doubled consonant). Every rule is checked as it is generated: its
positive must change to exactly the stated correction and its negative must not match at all. Run the generator,
then `python3 scripts/check-rule-packs.py engine/rules/packs/verb-complements.json` and `cargo test --release rules::`.

## Coverage map

Construction, then the rule ids that cover it.

"""

TAIL = """
## Already covered by the engine's own passes (no regex written)

| Construction | Base rule |
|---|---|
| enjoy / avoid / finish / suggest + "to" + verb, to the -ing form | `grammar.gerund_complement` (structure.rs) |
| "look forward to", "accustomed to", "opposed to", "committed to" + base verb | `grammar.prepositional_gerund` |
| "Let's to go" | `grammar.extra_to` |
| "ought go" | `grammar.missing_to` |
| "to" + a past form followed by an object ("need to calculated the size") | `grammar.infinitive_base` (forms.rs); the `topast.*` and `to3sg.*` rules here add the cases with no object word after |
| "interested about/at/of/on", "discuss about", "reply me", "explain me", "depend of" | `grammar.interested_in`, `grammar.discuss_about`, `usage.reply_to`, `usage.explain_to`, `usage.explain_to_moved`, `grammar.depends_on` |
| modal + inflected verb ("can goes") | `grammar.modal_*`, `grammar.modal_base` |
| "didn't went" | `grammar.didnt_base` |

## Deliberately left out, and why

* **stop to / stop -ing, remember, forget, try, regret, go on, mean**: both forms are grammatical with different
  meanings ("stopped to smoke" and "stopped smoking"), so no regex can say which one the writer meant.
* **spend time to V, a waste of time to V, no use to V, hard to V**: "I spend time to understand your needs" and
  "it is no use to cry" are accepted English; flagging them would be a false alarm.
* **can't stand to V, bear to V, dread to think, regret to inform**: valid infinitive uses.
* **recommend / advise / ask / tell / want + person + to V**: valid ("I recommend you to read it" is British
  English); only the wrong versions are listed ("suggest me to go").
* **committed / dedicated to + base verb, contribute to + base verb, adapt / adjust to + base verb**: corporate prose
  uses these widely and a purpose reading ("adapt to survive") is possible.
* **hope / expect / agree / promise + -ing**: "I hope seeing patients is not tiring" is a gerund subject; only the
  narrow "hope seeing you" is listed. "agree to being paid" is correct (prepositional "to").
* **have to + -ing, going to + -ing, start to + -ing without a pronoun before the verb**: "the commitment we have to
  making it work", "a claim to being based on" and "the start to following" are correct prepositional uses.
* **quit / keep / involve / practise / admit / deny with "to"**: "quit to start a company" and "admit to stealing"
  are valid; only the unambiguous governors are listed.
* **prefer X-ing to V, would like / love + -ing**: acceptable to many native speakers.
* **tell / ask + person + bare verb ("tell him go")**: usually a quotation with the punctuation missing.
* **be going + verb without "to" when "going" is followed by a place**: "going home", "going back" are not verbs.
* **Past forms identical to the participle after have/need/ought/about to** ("needs to sold"): that is a passive with
  "be" missing, not a wrong base verb, so those forms only follow want / try / decide / hope and similar.
* **Relative clauses and ellipsis**: "do all they can to help", "what you want you get", "the man I consider to be",
  "what it feels like to be old" are all valid and are kept out by requiring a clause start or a pronoun subject.
"""

FAMILIES = [
    ('gerund.', 'Gerund-only verb + "to" + verb, rewritten to -ing (recommend, consider, mind, miss, risk, delay, postpone, resist, deny, imagine, appreciate, dislike, detest, tolerate, anticipate, contemplate, feel like)'),
    ('togerund.', 'Infinitive-only verb + -ing + determiner, rewritten to "to" + base verb (refuse, afford, plan, hope)'),
    ('toing.', '"to" + -ing after a to-infinitive verb or adjective, rewritten to the base verb (want, need, try, plan, decide, hope, like, love, hate, prefer, wish, begin, start, continue, choose, learn, forget, remember, refuse, promise, manage, fail, offer, expect, intend, attempt, deserve, threaten, arrange, pretend, afford, seem, appear, tend, ought, able, unable, supposed, afraid)'),
    ('missingto.', 'Infinitive-only verb + bare verb, "to" inserted (want, need, decide, plan, hope, expect, promise, agree, refuse, manage, fail, afford, offer, wish, learn)'),
    ('adjmissing.', 'Adjective + bare verb, "to" inserted (able, willing, likely, supposed, glad, sorry, eager, determined, going)'),
    ('bare.', 'Bare infinitive where "to" does not belong (make / let / hear + object, every modal, "\'ll", can\'t / won\'t, do-support, had better, would rather, why not)'),
    ('objto.', 'Verb + person + bare verb, "to" inserted (allow, want, need, expect, force, enable, encourage, cause, invite, persuade, convince, urge, remind, permit, order, teach, instruct, compel, oblige, get, would like)'),
    ('suggest_me.', '"suggest me to go" to "suggest that I go" (six pronouns)'),
    ('want_that.', '"want that you come" to "want you to come" (four pronouns)'),
    ('idiom.', 'Verbs and phrases that take -ing or a preposition (worth, busy, capable, interested, insist, succeed, prevent / prohibit / discourage / deter + person, be used to, get used to, devoted, addicted, prior to, in addition to, resort, when it comes to, with a view to, object to, can\'t help, can\'t wait, look forward for, have difficulty, prefer than, discuss to, ask / inform / contact / join + to + person, without to, how about to, suggest / describe / mention + person)'),
    ('adjto.', 'Adjective, noun or question word + "to" + -ing (nice to meeting you, ready to starting, hard to finding, decision to going, how to making, in order to getting, so as to avoiding)'),
    ('topast.', '"to" + a past form instead of the base verb (want to came)'),
    ('to3sg.', '"to" + a third-person -s form instead of the base verb (want to goes)'),
    ('missingobj.', 'Transitive verb with no object after a modal or negative (install, unlock, approve, locate and their relatives); extends grammar.missing_object_after_modal'),
]

def write(path):
    by = collections.defaultdict(list)
    for rid, note in core.COVER:
        by[rid].append(note)
    out = [HEAD]
    for prefix, text in FAMILIES:
        ids = [r['id'] for r in core.RULES if r['id'].startswith('vcomp.' + prefix)]
        if not ids:
            continue
        out.append(f'### {text}\n\n{len(ids)} rules: ' + ', '.join(f'`{i}`' for i in ids) + '\n\n')
    out.append(TAIL)
    open(path, 'w').write(''.join(out))
