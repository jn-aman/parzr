#!/usr/bin/env python3
"""Builds engine/rules/packs/modifiers.json and docs/rule-packs/modifiers.md (see ../gen-modifiers.py)."""
import json, pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import core
import fam_comp, fam_adv, fam_adv2, fam_adv3, fam_neg, fam_num, fam_misc, fam_extra

FAMILIES = [fam_comp, fam_adv, fam_adv2, fam_adv3, fam_neg, fam_num, fam_misc, fam_extra]

def write_doc(root):
    lines = ['# Modifiers pack: coverage map', '',
             f'`engine/rules/packs/modifiers.json` holds {len(core.RULES)} rules (id prefix `mod.`), generated by `scripts/modifiers-pack/build.py` '
             '(`python3 scripts/modifiers-pack/build.py` rewrites the JSON and this file). Every rule has a required literal, a positive and a '
             'negative example written for it, and is context-anchored: an adjective or adverb is judged only where the clause ends or a word '
             'that cannot be a noun follows, so attributive uses ("good, clean football", "too much hot water") are never touched. '
             '`scripts/modifiers-pack/e2e.py` runs every example through the built engine.', '',
             'Constructions the engine\'s own passes already fix are not repeated (see the notes in each section): usage.verb_well, usage.did_well, '
             'usage.feel_badly, usage.irregular_*, usage.elder_than, usage.double_comparative, grammar.more_comparative, grammar.most_superlative, '
             'grammar.negative_object_anything, grammar.negative_determiner_any, grammar.participle_adjective, usage.participle_ing, '
             'grammar.worst_case, usage.equally_as, and the hyphen pass for "a 30 day trial" / "a 5 year old" (marks.rs).', '']
    sections = {}
    for sec, cons, ids in core.COVER:
        sections.setdefault(sec, []).append((cons, ids))
    for sec, rows in sections.items():
        lines += [f'## {sec}', '', '| Construction | Rules |', '|---|---|']
        for cons, ids in rows:
            short = [i[4:] for i in ids]
            shown = ', '.join(f'`{s}`' for s in short[:8]) + (f' and {len(short) - 8} more' if len(short) > 8 else '')
            lines.append(f'| {cons.replace("|", "/")} | {len(ids)} rule(s): {shown} |')
        lines.append('')
    lines += ['## Deliberately left out', '',
              '- **doing good / did good (charity), feel badly, drive safe, travel safe, think different, play nice, hold tight, go slow, run free, feel free, loud and clear**: standard or idiomatic; no rule.',
              '- **good / well with commas** ("plays good, clean football"): two adjectives; the pack never treats a comma as the end of the clause for "good".',
              '- **more good / more bad / more big before a noun or "than"**: "more good news", "more bad than good", "more big than small" are correct; only the clause-final or "to/for/now" positions are flagged.',
              '- **more perfect, more complete, more equal, very complete, very essential, somewhat unique, quite unique**: widely used and accepted ("a more perfect union").',
              '- **very delighted / furious / exhausted / hilarious**: in wide use; only the clearly extreme list is a Style note (excellent, fantastic, terrific, enormous, gigantic, immense, huge, outstanding, magnificent, superb, marvelous, freezing, boiling, starving, spotless, priceless).',
              '- **too vs very, so ... that, quite, almost all, firstly/secondly, farther/further, fewer/less, the most / most**: correct or a preference.',
              '- **real quick, real soon, real time, a real good friend**: idiom or a different word class. "Real good" with a copula is a Register suggestion at 0.74 (informal AmE); first-person feelings ("I was real angry") are left because that is how chat is typed.',
              '- **freely/free, closely/close, rightly/right, directly/direct** and the other flat adverbs: both forms are standard with different meanings.',
              '- **ain\'t got no, don\'t got no, ain\'t nothing**: dialect or chat; the engine\'s own rule turns "don\'t got" into "don\'t have". "Is not nothing" (litotes) and "take no for an answer", "say no to" are never touched.',
              '- **alot / a lot**: owned by the confusions pack and the spelling pass.',
              '- **better then, bigger then**: confusions pack (then/than); **different than, prefer than, superior than, as good than**: prepositions pack.',
              '- **the more ... the more better, more better**: grammar.more_comparative.',
              '- **I only can, also placement, adverb order**: the word-order pass (grammar.adverb_position); the pack skips placement.',
              '- **he/she doesn\'t hardly + verb**: needs verb inflection, so only the I/we/you/they form is a rule.',
              '- **hardly + any, as more as possible**: ambiguous between "any more" and "as much", so no rule.',
              '- **real-time modes (professional/friendly tone)**: tone-mode rules do not run in the model build, so the pack uses Fix-mode rules only.', '']
    (root / 'docs/rule-packs/modifiers.md').write_text('\n'.join(lines))


def main():
    for f in FAMILIES:
        f.build()
    if core.ERRORS:
        print('\n'.join(core.ERRORS))
        sys.exit(f'{len(core.ERRORS)} rule(s) failed their own examples')
    root = HERE.parent.parent
    out = root / 'engine/rules/packs/modifiers.json'
    out.write_text(json.dumps(core.RULES, ensure_ascii=False, indent=2) + '\n')
    (HERE / 'expected.json').write_text(json.dumps(core.EXPECTED, ensure_ascii=False, indent=1))
    write_doc(root)
    print(len(core.RULES), 'rules ->', out)

if __name__ == '__main__':
    main()
