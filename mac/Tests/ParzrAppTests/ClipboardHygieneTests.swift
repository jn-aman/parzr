import XCTest
import AppKit
@testable import Parzr

/// The staged paste is hidden from clipboard managers. Runs on a private named pasteboard: the owner's clipboard is never touched.
@MainActor
final class ClipboardHygieneTests: XCTestCase {
    private func privateBoard() -> NSPasteboard {
        let board = NSPasteboard(name: NSPasteboard.Name("app.parzr.tests.ClipboardHygiene.\(UUID().uuidString)"))
        addTeardownBlock { @MainActor in board.releaseGlobally() }
        return board
    }
    func testTheStagedItemCarriesEveryClipboardManagerMarker() throws {
        let board = privateBoard()
        let transaction = ClipboardTransaction(board: board)
        try transaction.stage("I received your message.", attributed: NSAttributedString(string: "I received your message."))
        let item = try XCTUnwrap(board.pasteboardItems?.first)
        XCTAssertEqual(item.string(forType: .string), "I received your message.")
        for type in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
            XCTAssertTrue(item.types.contains(NSPasteboard.PasteboardType(type)), type)
        }
        XCTAssertTrue(item.types.contains(.rtf), "formatting still rides along")
        transaction.restoreUnconditionally()
    }
    func testRestoringPutsBackTheWritersOwnClipboardWithoutTheMarkers() throws {
        let board = privateBoard()
        board.clearContents(); board.setString("the writer's copy", forType: .string)
        let transaction = ClipboardTransaction(board: board)
        try transaction.stage("staged")
        transaction.restore()
        let item = try XCTUnwrap(board.pasteboardItems?.first)
        XCTAssertEqual(item.string(forType: .string), "the writer's copy")
        XCTAssertTrue(Set(item.types).isDisjoint(with: ClipboardTransaction.hiddenTypes), "the writer's own item is put back as it was")
    }
    func testAWritersConcealedCopyStaysConcealedAfterRestore() throws {
        let board = privateBoard()
        let original = NSPasteboardItem(); original.setString("hunter2", forType: .string); ClipboardTransaction.hide(original)
        board.clearContents(); board.writeObjects([original])
        let transaction = ClipboardTransaction(board: board)
        try transaction.stage("staged")
        transaction.restore()
        let item = try XCTUnwrap(board.pasteboardItems?.first)
        XCTAssertEqual(item.string(forType: .string), "hunter2")
        XCTAssertTrue(item.types.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")), "a password manager's marker survives the round trip")
    }
}
